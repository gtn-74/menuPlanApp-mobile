// 日付文字列から年月を取得
export const getYearMonth = (dateString: string): { year: number; month: number } => {
  const [year, month] = dateString.split('-').map(Number);
  return { year, month };
};

// 特定の日付のデータを取得
export const getDataForDate = (date: string) => {
  return {
    menus: mockMenuItems.filter((item) => item.date === date),
    budgets: mockBudgetItems.filter((item) => item.date === date),
    events: mockEvents.filter((item) => item.date === date),
    todos: mockTodoItems.filter((item) => item.date === date),
  };
};

// 月全体のデータを取得
export const getDataForMonth = (year: number, month: number) => {
  const monthStr = month.toString().padStart(2, '0');
  const yearMonthPrefix = `${year}-${monthStr}`;

  return {
    menus: mockMenuItems.filter((item) => item.date.startsWith(yearMonthPrefix)),
    budgets: mockBudgetItems.filter((item) => item.date.startsWith(yearMonthPrefix)),
    events: mockEvents.filter((item) => item.date.startsWith(yearMonthPrefix)),
    todos: mockTodoItems.filter((item) => item.date.startsWith(yearMonthPrefix)),
  };
};
